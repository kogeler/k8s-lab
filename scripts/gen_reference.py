#!/usr/bin/env python3
"""Render the generated reference pages under doc/reference/ from the code.

  roles.md      every role's entry points and inputs (meta/argument_specs.yml,
                defaults from defaults/main.yml)
  terraform.md  the modules' terraform-docs READMEs, one section each
  charts.md     every chart's metadata (Chart.yaml) and its values.yaml
  versions.md   one table of every pinned version, read from where it is pinned

`--check` (make check) fails when a page differs from what the code renders;
without it the pages are written.
"""
from __future__ import annotations

import json
import pathlib
import posixpath
import re
import sys
import tomllib

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "doc" / "reference"
HEADER = "<!-- Generated by scripts/gen_reference.py from the code; do not edit. -->\n\n"


def load(path: pathlib.Path):
    return yaml.safe_load(path.read_text())


def text(value) -> str:
    if isinstance(value, list):
        return " ".join(str(v).strip() for v in value)
    return str(value or "").strip()


def cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def code(value) -> str:
    shown = value if isinstance(value, str) else json.dumps(value)
    return f"`{cell(shown)}`" if shown != "" else '`""`'


def roles() -> str:
    out = [HEADER, "# Role reference\n\n",
           "The inputs of every role, from its `meta/argument_specs.yml` and `defaults/main.yml`. "
           "An input without a default is required. Common variables (`k8s_lab_*`) are described in "
           "the [variable contract](../variable-contract.md).\n"]
    for role in sorted((ROOT / "ansible" / "roles").iterdir()):
        specs = load(role / "meta" / "argument_specs.yml")["argument_specs"]
        defaults_file = role / "defaults" / "main.yml"
        defaults = (load(defaults_file) or {}) if defaults_file.exists() else {}
        out.append(f"\n## {role.name}\n\n")
        for entry, spec in specs.items():
            title = "" if entry == "main" else f"### Entry point `{entry}`\n\n"
            out.append(title)
            out.append(f"{text(spec.get('short_description'))}. {text(spec.get('description'))}\n\n")
            options = spec.get("options") or {}
            if not options:
                continue
            out.append("| Input | Type | Default | Description |\n|---|---|---|---|\n")
            for name, opt in options.items():
                default = "required" if opt.get("required") or name not in defaults else code(defaults[name])
                kind = opt.get("type", "")
                if kind == "list" and opt.get("elements"):
                    kind = f"list of {opt['elements']}"
                out.append(f"| `{name}` | {kind} | {default} | {cell(text(opt.get('description')))} |\n")
            out.append("\n")
        out.append(f"README: [ansible/roles/{role.name}](../../ansible/roles/{role.name}/README.md)\n")
    return "".join(out)


def terraform() -> str:
    out = [HEADER, "# Terraform module reference\n\n",
           "The modules' inputs, outputs and requirements, as `terraform-docs` renders them into each "
           "module's README (`make check` keeps those current).\n"]
    for module in ["workload_cluster", "workload_addons", "workload_addons/modules/access"]:
        readme = (ROOT / "terraform" / "modules" / module / "README.md").read_text()
        # The README's relative links start at the module's directory.
        base = f"../../terraform/modules/{module}"
        readme = re.sub(r"\]\((?![a-z]+:|#)([^)]+)\)",
                        lambda m: f"]({posixpath.normpath(posixpath.join(base, m.group(1)))})", readme)
        # terraform-docs gives every module the same anchors (input_cluster, …):
        # prefix them per module so a link lands in its own module's table.
        slug = module.replace("/", "-").replace("_", "-")
        readme = re.sub(r'<a name="([^"]+)"></a>', lambda m: f'<a name="{slug}-{m.group(1)}"></a>', readme)
        readme = re.sub(r"\]\(#([^)]+)\)", lambda m: f"](#{slug}-{m.group(1)})", readme)
        body = re.sub(r"(?m)^(#+) ", lambda m: "#" + m.group(1) + " ", readme)
        body = re.sub(r"(?m)^## .*\n", "", body, count=1)
        out.append(f"\n## `terraform/modules/{module}`\n\n{body.strip()}\n")
    return "".join(out)


def charts() -> str:
    out = [HEADER, "# Chart reference\n\n",
           "Every chart's metadata and its `values.yaml` with the comments that document each value.\n"]
    for chart in sorted((ROOT / "charts").iterdir()):
        meta = load(chart / "Chart.yaml")
        out.append(f"\n## {meta['name']}\n\n{text(meta.get('description'))}\n\n")
        out.append(f"Version `{meta['version']}`, appVersion `{meta.get('appVersion', '')}`.")
        for dep in meta.get("dependencies") or []:
            out.append(f" Dependency `{dep['name']}` `{dep['version']}` from {dep['repository']}.")
        if (chart / "values.schema.json").exists():
            out.append(" `values.schema.json` validates the values (`additionalProperties: false`).")
        else:
            out.append(" No schema: the values pass through to the upstream chart.")
        out.append(f"\n\n```yaml\n{(chart / 'values.yaml').read_text().strip()}\n```\n")
    return "".join(out)


def versions() -> str:
    ref = load(ROOT / "tests" / "playbooks" / "group_vars" / "all.yml")
    group_vars = "tests/playbooks/group_vars/all.yml"
    rows = [
        ("Kubernetes (node images `capi:kubeadm/<version>`)", ref["k8s_lab_kubernetes_version"], group_vars),
        ("k3s (bootstrap cluster)", ref["k8s_lab_k3s_version"], group_vars),
        ("kubectl on the host", ref["k8s_lab_kubectl_version"], group_vars),
        ("Cluster API and clusterctl", ref["k8s_lab_clusterctl_version"], group_vars),
        ("cert-manager", f"the one clusterctl {ref['k8s_lab_clusterctl_version']} installs", group_vars),
        ("CAPN", ref["k8s_lab_capn_provider_version"], group_vars),
        ("LXD snap channel", load(ROOT / "ansible/roles/lxd/defaults/main.yml")["lxd_snap_channel"],
         "ansible/roles/lxd/defaults/main.yml"),
    ]
    for chart in sorted((ROOT / "charts").iterdir()):
        for dep in load(chart / "Chart.yaml").get("dependencies") or []:
            rows.append((f"{dep['name']} chart", dep["version"], f"charts/{chart.name}/Chart.yaml"))
    for values in sorted((ROOT / "charts").glob("*/values.yaml")):
        for image in re.findall(r'(?m)^\s*\w*[iI]mage:\s*"([^"]+@sha256:[0-9a-f]+)"', values.read_text()):
            name, digest = image.split("@")
            rows.append((f"image `{name.rsplit(':', 1)[0]}`", f"{name.rsplit(':', 1)[1]} (by digest)",
                         str(values.relative_to(ROOT))))
    fixture = ROOT / "tests/fixtures/terraform/workload-clusters/lab-default"
    providers: dict[str, dict[str, str]] = {}
    for lock in sorted(fixture.glob("*/.terraform.lock.hcl")):
        for name, version in re.findall(r'provider "registry.terraform.io/([^"]+)" \{\s*version\s*=\s*"([^"]+)"',
                                        lock.read_text()):
            providers.setdefault(name, {})[lock.parent.name] = version
    for name, by_root in sorted(providers.items()):
        if len(set(by_root.values())) == 1:
            rows.append((f"Terraform provider `{name}`", next(iter(by_root.values())), "fixture `.terraform.lock.hcl`"))
        else:  # the roots disagree: one row each, so the difference shows
            for root, version in sorted(by_root.items()):
                rows.append((f"Terraform provider `{name}` ({root} root)", version, "fixture `.terraform.lock.hcl`"))
    for line in (ROOT / ".tool-versions").read_text().splitlines():
        if line.strip() and not line.startswith("#"):
            tool, version = line.split()[:2]
            rows.append((f"{tool} (runner)", version, ".tool-versions"))
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    direct = [*project["project"]["dependencies"], *sum(project.get("dependency-groups", {}).values(), [])]
    locked = {p["name"]: p["version"] for p in tomllib.loads((ROOT / "uv.lock").read_text())["package"]}
    for dep in direct:
        name = re.split(r"[<>=!~ \[]", dep, maxsplit=1)[0]
        rows.append((f"{name} (Python, runner)", locked.get(name, "?"), "uv.lock"))
    for coll in load(ROOT / "ansible" / "requirements.lock.yml")["collections"]:
        rows.append((f"collection `{coll['name']}`", coll["version"], "ansible/requirements.lock.yml"))
    vagrantfile = (ROOT / "tests/vagrant/debian13/Vagrantfile").read_text()
    box = re.search(r'config\.vm\.box\s*=\s*"([^"]+)"', vagrantfile).group(1)
    box_version = re.search(r'config\.vm\.box_version\s*=\s*"([^"]+)"', vagrantfile).group(1)
    rows.append((f"harness VM box `{box}`", box_version, "tests/vagrant/debian13/Vagrantfile"))
    workflows = sorted((ROOT / ".github" / "workflows").glob("*.yml"))
    runners = sorted({m for f in workflows for m in re.findall(r"runs-on:\s*(\S+)", f.read_text())})
    rows.append(("GitHub Actions runner", ", ".join(runners), ".github/workflows/"))
    actions = sorted({m for f in workflows
                      for m in re.findall(r"uses:\s*([\w.-]+/[\w./-]+)@([0-9a-f]{40})\s*#\s*(\S+)", f.read_text())})
    for action, sha, tag in actions:
        rows.append((f"action `{action}`", f"{tag} ({sha[:12]})", ".github/workflows/"))
    out = [HEADER, "# Versions\n\n",
           "Every version the project pins, read from the file that pins it. Binaries the host "
           "downloads are checked against the sha256 pinned beside their version.\n\n",
           "| Component | Version | Pinned in |\n|---|---|---|\n"]
    out += [f"| {c} | `{v}` | `{p}` |\n" if not p.startswith("fixture") else f"| {c} | `{v}` | {p} |\n"
            for c, v, p in rows]
    return "".join(out)


PAGES = {"roles.md": roles, "terraform.md": terraform, "charts.md": charts, "versions.md": versions}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, render in PAGES.items():
        page = OUT / name
        content = render()
        if check:
            if not page.exists() or page.read_text() != content:
                stale.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            page.write_text(content)
    if stale:
        print(f"doc/reference is stale ({', '.join(stale)}): run scripts/gen_reference.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
